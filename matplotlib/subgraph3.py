import matplotlib.pyplot as plt
plt.subplot(2,2,1)
plt.plot([1,2,3],[10,20,30])
plt.title("Line Graph")
plt.subplot(2,2,2)
plt.bar(["A","B","C"],[10,20,30])
plt.title("Bar Graph")
plt.subplot(2,2,3)
plt.scatter([1,2,3],[30,10,20])
plt.title("Scatter Graph")
plt.subplot(2,2,4)
plt.pie([40,30,20,10],labels=["A","B","C","D"])
plt.title("Pie Chart")
plt.tight_layout()
plt.show()